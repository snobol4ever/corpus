#!/usr/bin/env python3
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'syntaxes', 'scrip-fences.tmLanguage.json')
BASE = os.path.join(HERE, 'syntaxes', 'scriptix.tmLanguage.json')
ROWS = [('snobol4', 'snobol4|snobol|spitbol|scrip', 'source.snobol4'), ('snocone', 'snocone', 'source.sc'), ('rebus', 'rebus', 'source.reb'), ('icon', 'icon|unicon', 'source.icn'),
        ('prolog', 'prolog', 'source.pl'), ('pascal', 'pascal', 'source.pascal'), ('raku', 'raku', 'source.raku')]
OPEN = '(^|\\G)(\\s*)(`{3,}|~{3,})\\s*(?i:(%s)((\\s+|:|,|\\{|\\?)[^`]*)?$)'
CLOSE = '(^|\\G)(\\2|\\s{0,3})(\\3)\\s*$'
WHILE = '(^|\\G)(?!\\s*([`~]{3,})\\s*$)'


def rule(ident, tags, scope):
    return {'begin': OPEN % tags, 'name': 'markup.fenced_code.block.markdown', 'end': CLOSE,
            'beginCaptures': {'3': {'name': 'punctuation.definition.markdown'}, '4': {'name': 'fenced_code.block.language.markdown'}, '5': {'name': 'fenced_code.block.language.attributes.markdown'}},
            'endCaptures': {'3': {'name': 'punctuation.definition.markdown'}},
            'patterns': [{'begin': '(^|\\G)(\\s*)(.*)', 'while': WHILE, 'contentName': 'meta.embedded.block.' + ident + ' ' + scope, 'patterns': [{'include': scope}]}]}


def grammar():
    return {'scopeName': 'scrip.fences.injection', 'injectionSelector': 'L:text.html.markdown, L:text.scriptix',
            'comment': 'GENERATED by gen_fences.py, never edited: a fence of a SCRIP language, opened as CommonMark reads it (the first word of its info string), is that language\'s own text',
            'patterns': [rule(*r) for r in ROWS]}


def base():
    return {'scopeName': 'text.scriptix', 'name': 'SCRIPtix', 'comment': 'GENERATED by gen_fences.py, never edited: a .scrip file is a markdown text whose fences of a SCRIP language are injected as in a .md', 'patterns': [{'include': 'text.html.markdown'}]}


def main(a):
    files = [(OUT, json.dumps(grammar(), indent=2) + '\n'), (BASE, json.dumps(base(), indent=2) + '\n')]
    if a[:1] == ['--check']:
        stale = [p for p, w in files if (open(p, encoding='utf-8').read() if os.path.exists(p) else '') != w]
        print('SCRIP_FENCES ' + ('STALE ' + ' '.join(os.path.basename(p) for p in stale) if stale else 'current'))
        return 1 if stale else 0
    for p, w in files:
        open(p, 'w', encoding='utf-8').write(w)
        print('SCRIP_FENCES wrote ' + p)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
