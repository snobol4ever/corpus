    t(\+ \+ (term_hash(f(a, [b]), H1), term_hash(f(a, [b]), H2), integer(H1), H1 == H2)),
    t(\+ \+ (term_hash(f(a), -1, 10, H), integer(H), H >= 0, H < 10)),
    t(term_hash(a, _, 0, _)),
    t(term_hash(a, x, 0, _)),
