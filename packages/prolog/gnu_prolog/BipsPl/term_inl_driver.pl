    t(\+ \+ (term_ref(f(a, X), R), integer(R))),
    t(\+ \+ (copy_term(g(X, b), T), term_ref(T, R), term_ref(T2, R), T2 == T)),
    t(term_ref(_, _)),
    t(term_ref(a, x)),
    t(term_ref(_, -1)),
    t((X = f(X), acyclic_term(X))),
    true.
