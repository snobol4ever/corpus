    t(1.5 @< 1),
    t((b @=< b)),
    t((f(a) @> a)),
    t((g(b) @>= g(a))),
    t((g(a) @>= g(b))),
    t(arg(2, f(a, b, c), _)),
    t(arg(1, [x|y], _)),
    t(arg(4, f(a), _)),
    t(arg(0, f(a), _)),
    t(arg(_, f(a, b), _)),
    t(arg(1, foo, _)),
    t(arg(a, f(a), _)),
    t(arg(-1, f(a), _)),
    t(functor(f(a, b), _, _)),
    t(functor([_|_], _, _)),
    t(functor(abc, _, _)),
    t(functor(_, f, 3)),
    t(functor(_, 1.5, 0)),
    t(functor(_, _, 2)),
    t(functor(_, f(a), 1)),
    t(functor(_, f, -1)),
    t(functor(_, 1.5, 1)),
    t(_ =.. [f, a, b]),
    t((f(a, g(b)) =.. _)),
    t(_ =.. [foo]),
    t(1.5 =.. _),
    t(_ =.. []),
    t(_ =.. [f(a), b]),
    t(_ =.. _),
    t(copy_term(f(X, Y, X), _)),
    t(copy_term(f(X), f(a))),
    t(copy_term(a, b)),
    t(copy_term(_, _)),
    t(setarg(1, f(a, b), z)),
    t((copy_term(f(a), T), (setarg(1, T, b), fail ; true), arg(1, T, _))),
    t((copy_term(f(a, b), T), setarg(2, T, g(x)), arg(2, T, _))),
    t(setarg(3, f(a), z)),
    t(setarg(_, f(a), z)),
    t(setarg(a, f(a), z)),
    t(setarg(1, foo, z)),
    t(setarg(-1, f(a), z)),
    t(setarg(1, f(a, b), z, true)),
    t((copy_term(f(a), T), (setarg(1, T, b, false), fail ; true), arg(1, T, _))),
    t((copy_term(f(a), T), (setarg(1, T, b, true), fail ; true), arg(1, T, _))),
    t(setarg(1, f(a), g(x), false)),
    t(setarg(1, f(a), z, maybe)),
    t(setarg(1, f(a), z, _)),
    t(term_variables(f(X, g(Y, X), _), _)),
