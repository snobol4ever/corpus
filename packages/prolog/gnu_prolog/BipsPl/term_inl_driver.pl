% term_inl_driver.pl -- grades GNU Prolog's BipsPl/term_inl.pl through the predicates it defines (Lon via the ceo, CEO-1523: every
% Prolog source file of the GNU package is graded through a driver; CEO-700, CEO-1269: a library is graded by its driver,
% NAME_driver beside it). gprolog's answer is term_inl.pl's own code; SCRIP is graded three-way against it (m3 = m4 = gprolog).
% Every predicate is called in a mode GNU Prolog's manual documents; an error prints as its ISO formal term only.
% NOT DRIVEN: nb_setarg/3 -- absent from the reference gprolog 1.4.5 (existence_error(procedure,nb_setarg/3)); the vendored term_inl.pl is 1.6.0
% Operator heads ((==)/2, (@<)/2, (=..)/2 ...) whose left operand is a compound or an atom are written t((L op R)): the extra
% parentheses only group. term_hash/2,4 and term_ref/2 values are implementation numbers: they are tested by a property
% under \+ \+ so no number prints (a Range of 1 is the one documented value: 0 =< Hash < 1). A setarg/3,4 effect is shown
% on a fresh copy_term/2 copy read back by arg/3, so the conjunction calls term_inl.pl predicates only.
:- initialization(main).

% t(G): every solution of G, or the formal error term G raises.
t(G) :- copy_term(G, C),
        catch(findall(C, C, L), E, true),
        (   var(E) -> R = L
        ;   E = error(F, _) -> R = error(F)
        ;   R = ball(E)
        ),
        \+ \+ ( numbervars(G-R, 0, _), writeq(G), write(' => '), writeq(R), nl ).

% o(G): for a goal whose effect is OUTPUT -- what it printed between < and >, then true, fail or the formal error term.
o(G) :- write('<'),
        catch(( G -> R = true ; R = fail ), E, ( E = error(F, _) -> R = error(F) ; R = ball(E) )),
        write('> '), writeq(R), nl.

main :-
    t(compare(_, 1, a)),
    t(compare(_, f(a), f(a))),
    t(compare(_, b, a)),
    t(compare(_, 1.0, 1)),
    t(compare(_, f(b), g(a, a))),
    t(compare(<, a, b)),
    t(compare(=, a, b)),
    t(compare(foo, a, b)),
    t(compare(1, a, b)),
    t(X == X),
    t((f(X, a) == f(X, a))),
